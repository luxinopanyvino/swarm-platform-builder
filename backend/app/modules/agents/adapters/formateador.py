import logging
from typing import Dict, Any

from app.core.config import settings
from app.shared.llm import call_llm, get_default_model

logger = logging.getLogger(__name__)

_FORMAT_LABELS = {
    "apa": "APA 7th edition",
    "ieee": "IEEE",
    "vancouver": "Vancouver",
    "chicago": "Chicago 17th edition",
    "nature": "Nature / NLM numbered",
}

_FORMAT_INSTRUCTIONS = {
    "apa": (
        "Use APA 7th edition style. In-text citations: (Author, Year). "
        "References section: Author, A. A. (Year). Title. Journal, Volume(Issue), pages. https://doi.org/..."
    ),
    "ieee": (
        "Use IEEE style. In-text citations: bracketed numbers [1], [2] in order of first appearance. "
        "References section: [1] A. Author, 'Title,' Journal, vol. X, no. Y, pp. Z–Z, Year."
    ),
    "vancouver": (
        "Use Vancouver style. In-text citations: superscript or bracketed sequential numbers. "
        "References section numbered in order of appearance: 1. Author AB. Title. Journal. Year;Vol(Issue):pages."
    ),
    "chicago": (
        "Use Chicago 17th edition author-date style. In-text citations: (Author Year, page). "
        "References section: Author. Year. Title. Publisher."
    ),
    "nature": (
        "Use Nature/NLM numbered style. In-text citations: superscript sequential numbers. "
        "References section: 1. Author, A. B. et al. Title. Journal Vol, pages (Year)."
    ),
}


# Generated by GitHub Copilot
async def run_formateador(state: Dict[str, Any]) -> Dict[str, Any]:
    """
    Formateador Agent.
    Applies a specific scientific citation format (APA, IEEE, Vancouver, Chicago, Nature)
    to the draft. Preserves all content; only rewrites in-text citations and the
    References/Bibliography section.
    """
    draft_text = state.get("draft_text") or ""
    if not draft_text:
        return {"formatted_text": ""}

    # Resolve format: agent_settings → state → default
    agent_cfg = (state.get("agent_settings") or {}).get("formateador", {})
    scientific_format = (
        agent_cfg.get("scientific_format")
        or state.get("scientific_format")
        or "apa"
    ).lower()

    # Resolve model: per-agent override → settings default
    model = agent_cfg.get("model") or get_default_model()

    format_label = _FORMAT_LABELS.get(scientific_format, scientific_format.upper())
    instruction = _FORMAT_INSTRUCTIONS.get(
        scientific_format,
        "Format references in APA 7th edition style.",
    )
    log = state.get("_log") or (lambda msg, level="info": None)

    logger.info(f"Running Formateador — format: {scientific_format}, model: {model}")
    log(f"📄 Aplicando formato {format_label} — modelo: {model} | {len(draft_text.split())} palabras")

    prompt = (
        f"You are a scientific manuscript formatter. Rewrite the manuscript below applying "
        f"{format_label} citation style.\n\n"
        f"MANDATORY RULES:\n"
        f"1. Copy the ENTIRE manuscript text verbatim, preserving every paragraph, section, and sentence.\n"
        f"2. Only modify in-text citations and the References section to match {format_label}.\n"
        f"3. If citations are missing, add generic placeholders such as (Author, {{}}) or [1].\n"
        f"4. Do NOT write explanations, steps, guides, or commentary of any kind.\n"
        f"5. Do NOT start with 'I can', 'I will', 'Here is', 'Sure', or any similar phrase.\n"
        f"6. Begin your output directly with the first line of the manuscript.\n\n"
        f"{format_label} format rules:\n{instruction}\n\n"
        f"--- MANUSCRIPT START ---\n"
        f"{draft_text}\n"
        f"--- MANUSCRIPT END ---\n\n"
        f"Output the complete reformatted manuscript now, starting with the title:"
    )

    # Patterns that indicate the model refused or provided meta-commentary instead of the manuscript
    _REFUSAL_PATTERNS = (
        "i can't provide",
        "i cannot provide",
        "i'm unable",
        "i am unable",
        "here's how to",
        "here is how to",
        "follow these steps",
        "to format the manuscript",
        "you can follow",
        "you should follow",
    )

    try:
        result = await call_llm(prompt, model=model, timeout=300.0, num_ctx=4096, keep_alive=0)
        # Detect model refusals / meta-commentary (model gave instructions instead of formatting)
        result_lower = result.lower()
        refused = any(pat in result_lower for pat in _REFUSAL_PATTERNS)
        if refused:
            logger.warning("Formateador: model produced a refusal/meta-commentary response; falling back to original draft.")
            return {"formatted_text": draft_text, "scientific_format": scientific_format}
        # Sanity check: if the result is much shorter than the original, the model
        # likely truncated — fall back to the original draft to avoid data loss.
        if result and len(result) >= len(draft_text) * 0.5:
            log(f"✅ Formato aplicado — {len(result.split())} palabras.")
            return {"formatted_text": result, "scientific_format": scientific_format}
        logger.warning(
            f"Formateador output suspiciously short ({len(result)} vs {len(draft_text)} chars); "
            "falling back to original draft."
        )
        log("⚠️ Resultado muy corto; usando borrador original sin cambios.", "warning")
        return {"formatted_text": draft_text, "scientific_format": scientific_format}
    except Exception:
        logger.exception("Error calling LLM in Formateador")
        log("⚠️ Error en formateo; usando borrador original.", "warning")
        return {"formatted_text": draft_text, "scientific_format": scientific_format}
