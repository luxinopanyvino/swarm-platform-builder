async def ensure_local_admin_user() -> None:
    """Ensure the local SQLite dev environment always has an admin login."""
    if not settings.DATABASE_URL.startswith("sqlite"):
        return

    # Read password from env; fall back to a dev-only default
    admin_password = os.environ.get("DEV_ADMIN_PASSWORD", "admin123")

    async with AsyncSessionLocal() as session:
        result = await session.execute(select(UserModel).where(UserModel.email == "admin@admin"))
        user = result.scalars().first()

        if user is None:
            user = UserModel(
                email="admin@admin",
                hashed_password=hash_password(admin_password),
                full_name="Admin",
                role=UserRole.ADMIN,
                is_active=True,
            )
            session.add(user)
        else:
            user.hashed_password = hash_password(admin_password)
            user.full_name = "Admin"
            user.role = UserRole.ADMIN
            user.is_active = True

        await session.commit()


